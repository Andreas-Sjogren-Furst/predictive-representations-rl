"""FB-specific validation of one trusted, locally saved Four Rooms checkpoint.

This is intentionally NOT a universal analysis capability: only FB can expose
F(s,a,z) and B(s). Numerical tabular occupancy lives in a generic module.
"""
from __future__ import annotations

from dataclasses import asdict
from hashlib import sha256
from pathlib import Path
import json
import math

import numpy as np

from aeris.analysis.four_rooms import build_four_rooms_oracle, load_policy_actions
from aeris.analysis.tabular import compare_deterministic_policy
from aeris.analysis.tabular_occupancy import centered_pearson, exact_discounted_occupancy
from aeris.environments import FourRooms


def _effective_rank(matrix: np.ndarray) -> float:
    """Entropy effective rank of centered state features; 0 if constant."""
    _, singular, _ = np.linalg.svd(matrix - matrix.mean(axis=0, keepdims=True), full_matrices=False)
    eig = singular ** 2
    if eig.sum() <= 1e-24:
        return 0.0
    p = eig[eig > 0] / eig.sum()
    return float(np.exp(-(p * np.log(p)).sum()))


def _cpu_agent_from_trusted_checkpoint(checkpoint_path: Path):
    # Security: torch checkpoints are pickle-capable. Only load a trusted local
    # checkpoint generated by AERIS, never uploaded or downloaded arbitrary data.
    import torch
    from aeris.agents.fb import DiscreteFBAgent, DiscreteFBConfig

    checkpoint = torch.load(checkpoint_path, map_location='cpu', weights_only=False)
    if not isinstance(checkpoint, dict) or 'agent' not in checkpoint:
        raise ValueError('not an AERIS FB checkpoint')
    payload = checkpoint['agent']
    saved_config = payload['config']
    config = DiscreteFBConfig(**{**saved_config, 'device': 'cpu'})
    agent = DiscreteFBAgent(config)
    # Device portability: permit a GPU checkpoint to be inspected on CPU,
    # with no changes to model hyperparameters or learned weights.
    payload = {**payload, 'config': asdict(config)}
    agent.load_state_dict(payload)
    agent.forward_network.eval()
    agent.backward_network.eval()
    agent.forward_target_network.eval()
    agent.backward_target_network.eval()
    return agent



def _validate_oracle_dataset(root: Path, manifest: dict, env: FourRooms) -> None:
    """Verify uniform state-action coverage instead of trusting a dataset label."""
    path = root / 'dataset.npz'
    expected_hash = manifest['experiment']['dataset']['settings'].get('sha256')
    if not path.is_file():
        raise ValueError('saved oracle dataset.npz is missing')
    if expected_hash and sha256(path.read_bytes()).hexdigest() != expected_hash:
        raise ValueError('dataset fingerprint differs from run manifest')
    with np.load(path, allow_pickle=False) as saved:
        obs = saved['observations']
        actions = saved['actions']
        nxt = saved['next_observations']
    needed = len(env.positions) * env.num_actions
    if (obs.shape != (needed, env.observation_dim)
            or nxt.shape != obs.shape or actions.shape != (needed,)):
        raise ValueError('oracle dataset must contain exactly one sample per state-action')
    observed = set()
    for o, a, after in zip(obs, actions, nxt):
        pos = env.position_of(o)
        if not isinstance(a, (np.integer, int)) or not 0 <= int(a) < env.num_actions:
            raise ValueError('oracle dataset contains invalid action')
        if env.position_of(after) != env.next_position(pos, int(a)):
            raise ValueError('oracle dataset contains incorrect transition')
        observed.add((pos, int(a)))
    if len(observed) != needed:
        raise ValueError('oracle dataset contains duplicate or missing state-actions')


def analyze_fb_checkpoint(run_dir: str | Path, *, save: bool = True) -> dict:
    """Diagnose representation occupancy and policy action ranking for a goal.

    Only applies the uniform-state-density comparison to the explicitly saved
    full-coverage oracle dataset. Does not claim numerical equivalence to the
    original paper or to terminal goal-reaching reward evaluation.
    """
    import torch
    root = Path(run_dir)
    manifest = json.loads((root / 'manifest.json').read_text(encoding='utf-8'))
    if manifest.get('status') != 'completed':
        raise ValueError('run must be completed')
    experiment = manifest['experiment']
    if experiment['environment']['name'] != 'four_rooms':
        raise ValueError('only Four Rooms is supported')
    dataset = experiment['dataset']
    if dataset['settings'].get('origin') != 'oracle':
        raise ValueError('occupancy comparison requires the saved uniform-coverage oracle dataset')
    targets = experiment['evaluation']['targets']
    if len(targets) != 1:
        raise ValueError('exactly one evaluation task is required')
    settings = targets[0]['task']['settings']
    goal = (int(settings['goal_row']), int(settings['goal_col']))
    env = FourRooms()
    _validate_oracle_dataset(root, manifest, env)
    agent = _cpu_agent_from_trusted_checkpoint(root / 'checkpoint.pt')
    if agent.config.observation_dim != env.observation_dim or agent.config.num_actions != env.num_actions:
        raise ValueError('checkpoint is incompatible with Four Rooms')
    oracle = build_four_rooms_oracle(env, goal, gamma=agent.config.gamma)
    n = len(oracle.positions)
    obs = np.stack([env.observation_for(pos) for pos in oracle.positions])
    with torch.no_grad():
        observations = agent._observations(obs)
        goal_z = agent.goal_condition(env.observation_for(goal))
        zs = agent._conditions(goal_z, batch_size=n)
        f = agent.forward_network(observations, zs).cpu().numpy()        # S, d, A
        b = agent.backward_network(observations).cpu().numpy()          # S, d
        f_target = agent.forward_target_network(observations, zs)
        q_target = torch.einsum('sda,sd->sa', f_target, zs)
        policy = torch.softmax(q_target / agent.config.temperature, dim=-1).cpu().numpy()
        learned_q = np.einsum('sda,sd->sa', f, zs.cpu().numpy())
        predicted_occupancy_density = np.einsum('sda,td->sat', f, b)

    if not np.isfinite(learned_q).all() or not np.isfinite(predicted_occupancy_density).all():
        raise ValueError('nonfinite network predictions')
    # Oracle dataset is uniform over (state, action), hence rho(state)=1/S.
    expected_occupancy_density = n * exact_discounted_occupancy(
        oracle.next_state_indices, policy, gamma=agent.config.gamma
    )
    non_goal = np.arange(n) != oracle.goal_index
    saved_policy = root / 'policy_final.npz'
    if saved_policy.exists():
        snapshot_actions = load_policy_actions(saved_policy, oracle, num_actions=env.num_actions)
        if not np.array_equal(snapshot_actions, np.argmax(learned_q, axis=1)):
            raise ValueError('saved final policy snapshot disagrees with the checkpoint')
    # Compare relative action advantages, not absolute Q magnitudes. The FB
    # objective has density/normalization conventions unlike terminal returns.
    actual_goal = expected_occupancy_density[:, :, oracle.goal_index]
    centered_learned = learned_q - learned_q.mean(axis=1, keepdims=True)
    centered_exact = actual_goal - actual_goal.mean(axis=1, keepdims=True)
    a = np.argmax(learned_q, axis=1)
    best_exact = np.max(actual_goal, axis=1)
    agreement = actual_goal[np.arange(n), a] >= best_exact - 1e-8
    # The exact policy is induced by target F, not by the greedy online F.
    # This agreement tests ONE policy-improvement step against the induced pi.
    top_two = np.partition(learned_q, -2, axis=1)[:, -2:]
    margin = top_two[:, 1] - top_two[:, 0]
    entropy = -np.sum(policy * np.log(np.maximum(policy, 1e-300)), axis=1)
    first_hit = compare_deterministic_policy(
        a.astype(np.int64), oracle.next_state_indices, oracle.optimal,
        goal_index=oracle.goal_index,
        max_steps=int(experiment['evaluation']['protocol']['settings']['max_steps']),
        shortest_distances=oracle.shortest_distances,
    )
    report = {
        'schema_version': 1,
        'analysis': 'fb_four_rooms_checkpoint_v1',
        'run_id': manifest['run_id'],
        'checkpoint': 'checkpoint.pt',
        'goal': list(goal),
        'number_of_states': n,
        'gradient_updates': agent.updates,
        'gamma': agent.config.gamma,
        'policy_temperature': agent.config.temperature,
        'dataset_assumption': 'oracle full-coverage, uniform state density',
        'policy_definition': 'Boltzmann of target F(s, a, z)^T z with training temperature',
        'occupancy_definition': 'discounted CURRENT-STATE visitation under continuing policy (no terminal state)',
        'evaluation_definition': 'first hitting goal within fixed horizon; terminal on entering goal',
        'backward_effective_rank': _effective_rank(b),
        'backward_goal_norm': float(np.linalg.norm(b[oracle.goal_index])),
        'target_policy_mean_entropy_nats': float(entropy.mean()),
        'target_policy_entropy_fraction_of_uniform': float(entropy.mean() / math.log(env.num_actions)),
        'learned_action_spread_mean': float(np.std(learned_q[non_goal], axis=1).mean()),
        'learned_action_margin_mean': float(margin[non_goal].mean()),
        'state_positions': [list(pos) for pos in oracle.positions],
        'state_action_improvement_agreement': [bool(item) for item in agreement],
        'learned_action_counts_non_goal': [int(np.sum(a[non_goal] == action)) for action in range(env.num_actions)],
        'exact_occupancy_correlation': centered_pearson(
            predicted_occupancy_density[non_goal], expected_occupancy_density[non_goal]),
        'goal_action_advantage_correlation': centered_pearson(centered_learned[non_goal], centered_exact[non_goal]),
        'goal_action_agreement_with_exact_policy_improvement': float(agreement[non_goal].mean()),
        'first_hit_goal_performance': first_hit.summary(),
    }
    if save:
        out = root / 'analysis' / 'fb_checkpoint_v1.json'
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(report, indent=2, allow_nan=False) + '\n', encoding='utf-8')
    return report
